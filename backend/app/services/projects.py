"""Project CRUD and workspace provisioning."""

from __future__ import annotations

import uuid

from sqlalchemy import func, select
from sqlalchemy.orm import Session

from app.models.clip import Clip
from app.models.project import Project
from app.models.video import Video
from app.schemas.projects import ProjectCreate, ProjectRead, ProjectUpdate
from app.services import workspace as workspace_service


def create_project(db: Session, data: ProjectCreate) -> Project:
    """Create a project row and scaffold its workspace directory.

    Everything generated by LongVid lives inside the workspace; the user's
    original files are never modified.
    """
    name = data.name.strip()
    if not name:
        raise ValueError("Project name must not be blank")

    description = data.description.strip() if data.description else None
    project_id = uuid.uuid4().hex
    project = Project(
        id=project_id,
        name=name,
        description=description,
        workspace_path=workspace_service.relative_workspace_path(project_id),
    )
    workspace_service.create_workspace(project_id)
    db.add(project)
    db.commit()
    db.refresh(project)
    return project


def get_project(db: Session, project_id: str) -> Project | None:
    """Fetch one project by id, or ``None``."""
    return db.get(Project, project_id)


def list_projects(db: Session) -> list[Project]:
    """All projects, newest first."""
    stmt = select(Project).order_by(Project.created_at.desc(), Project.id.desc())
    return list(db.execute(stmt).scalars())


def update_project(db: Session, project_id: str, data: ProjectUpdate) -> Project | None:
    """Apply a partial update. Returns the updated project or ``None``."""
    project = get_project(db, project_id)
    if project is None:
        return None

    fields = data.model_dump(exclude_unset=True)
    if "name" in fields:
        name = (fields["name"] or "").strip()
        if not name:
            raise ValueError("Project name must not be blank")
        project.name = name
    if "description" in fields:
        description = fields["description"]
        project.description = description.strip() if description else None
    if "status" in fields and fields["status"] is not None:
        project.status = fields["status"]

    db.commit()
    db.refresh(project)
    return project


def delete_project(db: Session, project_id: str) -> bool:
    """Delete a project, its rows, and its workspace directory."""
    project = get_project(db, project_id)
    if project is None:
        return False
    workspace_service.delete_workspace(project_id)
    db.delete(project)
    db.commit()
    return True


def to_read_model(db: Session, project: Project) -> ProjectRead:
    """Convert an ORM project into the API representation with counts."""
    video_count = db.execute(
        select(func.count()).select_from(Video).where(Video.project_id == project.id)
    ).scalar_one()
    clip_count = db.execute(
        select(func.count())
        .select_from(Clip)
        .join(Video, Video.id == Clip.video_id)
        .where(Video.project_id == project.id)
    ).scalar_one()
    return ProjectRead(
        id=project.id,
        name=project.name,
        description=project.description,
        status=project.status,
        workspace_path=project.workspace_path,
        video_count=video_count,
        clip_count=clip_count,
        created_at=project.created_at,
        updated_at=project.updated_at,
    )
